"""Write the notebooks' `#| export` cells to the Python modules in src/ (nbdev-style, no
extra dependency).

The notebooks in notebooks/ are the source code. A notebook names its default module once,
in a cell like `#| default_exp agents.merchant`. Every code cell that starts with
`#| export` is copied, in order, into src/agents/merchant.py. A cell that starts with
`#| export tools.risk` goes to src/tools/risk.py instead, so one notebook can hold several
small modules. The modules are what the graph, the other notebooks and the tests import.

    uv run python -m src.nbexport           # write all modules
    uv run python -m src.nbexport --check   # exit 1 if a module is out of date (the tests do this)

Never edit the generated modules by hand: the next export overwrites them. This file is the
one hand-written module besides the package __init__ files.
"""

import argparse
import ast
import itertools
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NOTEBOOKS = ROOT / "notebooks"


def _code_cells(nb_path: Path):
    nb = json.loads(nb_path.read_text(encoding="utf-8"))
    for cell in nb["cells"]:
        if cell["cell_type"] == "code":
            src = cell["source"]
            yield "".join(src) if isinstance(src, list) else src


def _join(chunks: list[str]) -> str:
    """Join cells like isort + ruff format would: one blank line after an import block
    unless a def or class follows, two blank lines everywhere else."""
    body = chunks[0]
    for prev, nxt in itertools.pairwise(chunks):
        try:
            last = ast.parse(prev).body[-1]
        except (SyntaxError, IndexError):
            last = None
        after_imports = isinstance(last, ast.Import | ast.ImportFrom)
        is_def = nxt.lstrip().startswith(("def ", "class ", "@", "async def "))
        body += ("\n\n" if after_imports and not is_def else "\n\n\n") + nxt
    return body


def _ruff_format(text: str, name: str) -> str:
    """Format with ruff when it is installed, so modules match `ruff format --check`."""
    ruff = shutil.which("ruff", path=str(Path(sys.executable).parent)) or shutil.which("ruff")
    if not ruff:
        return text
    res = subprocess.run(
        [ruff, "format", "--stdin-filename", name, "-"],
        input=text,
        capture_output=True,
        text=True,
        cwd=ROOT,
        check=False,
    )
    return res.stdout if res.returncode == 0 and res.stdout else text


def render(nb_path: Path) -> dict[Path, str]:
    """Module path -> module text for one notebook (empty if it exports nothing)."""
    default, chunks = None, {}
    for text in _code_cells(nb_path):
        first, _, rest = text.partition("\n")
        directive = first.strip()
        if directive.startswith("#| default_exp"):
            default = directive.split(maxsplit=2)[2].strip()
        elif directive.startswith("#| export"):
            parts = directive.split(maxsplit=2)
            module = parts[2].strip() if len(parts) == 3 else default
            if module is None:
                raise ValueError(f"{nb_path.name}: '#| export' before any '#| default_exp'")
            chunks.setdefault(module, []).append(rest.strip("\n"))
    rel = nb_path.relative_to(ROOT).as_posix()
    header = (
        f"# AUTO-GENERATED from {rel}. Do not edit this file: edit the notebook,\n"
        "# then run its last cell (or `uv run python -m src.nbexport`).\n"
    )
    out = {}
    for module, parts in chunks.items():
        target = ROOT / "src" / Path(*module.split(".")).with_suffix(".py")
        out[target] = _ruff_format(header + _join(parts) + "\n", target.name)
    return out


def export_all(check: bool = False, quiet: bool = False) -> list[Path]:
    """Export every notebook. Returns the modules that changed (or would change, with check)."""
    if os.getenv("NB_NO_EXPORT") and not check:
        if not quiet:
            print("NB_NO_EXPORT is set: export skipped")
        return []
    changed = []
    for nb_path in sorted(NOTEBOOKS.glob("*.ipynb")):
        for target, text in render(nb_path).items():
            old = target.read_text(encoding="utf-8") if target.exists() else None
            if old != text:
                changed.append(target)
                if not check:
                    target.parent.mkdir(parents=True, exist_ok=True)
                    target.write_text(text, encoding="utf-8")
    if not quiet:
        verb = "out of date" if check else "exported"
        names = ", ".join(p.relative_to(ROOT).as_posix() for p in changed) or "nothing changed"
        print(f"{verb}: {names}")
    return changed


def main() -> None:
    ap = argparse.ArgumentParser(description="Export notebook cells to src/ modules")
    ap.add_argument("--check", action="store_true", help="only report out-of-date modules")
    args = ap.parse_args()
    if export_all(check=args.check) and args.check:
        sys.exit(1)


if __name__ == "__main__":
    main()
